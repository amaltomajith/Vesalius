export const lerpPose = (a: Pose3, b: Pose3, k: number): Pose3 =>
  a.map((p, i) => [p[0] + (b[i][0] - p[0]) * k, p[1] + (b[i][1] - p[1]) * k, p[2] + (b[i][2] - p[2]) * k]);
