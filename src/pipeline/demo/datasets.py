"""The scans a person can pick in the interface, described in plain language.

`head` and `chest` are synthetic (generated by `dicom_series`); `rejected` is a real, public,
already-anonymous pydicom test file that has only ONE image, so the quality gate rejects it -- the
governance side of the pipeline, shown on purpose. Nothing here reads a real patient's data.
"""

from __future__ import annotations

import io
import zipfile
from dataclasses import dataclass, field

from pipeline.demo.dicom_series import PlantedIdentifier, build_demo_series


@dataclass(frozen=True)
class DatasetInfo:
    key: str
    title: str
    blurb: str
    shows: str  # what the person will see happen
    synthetic: bool
    preset: str  # the tissue the 3D model is made from ("" when the scan is rejected)
    expected: str  # "success" | "rejected"
    approx_seconds: int


DATASETS: dict[str, DatasetInfo] = {
    "head": DatasetInfo(
        key="head",
        title="Head scan",
        blurb="A synthetic head CT (106 images). The one to try first.",
        shows=(
            "Patient identifiers are stripped, the face is cut away for privacy, and you get a "
            "3D model of the head with no recognisable nose or face."
        ),
        synthetic=True,
        preset="skin_surface",
        expected="success",
        approx_seconds=90,
    ),
    "chest": DatasetInfo(
        key="chest",
        title="Chest scan",
        blurb="A synthetic chest CT (34 images).",
        shows=(
            "A chest needs no face removal, and the record says so explicitly. You get a 3D model "
            "of the spine, ribs and breastbone."
        ),
        synthetic=True,
        preset="bone",
        expected="success",
        approx_seconds=45,
    ),
    "rejected": DatasetInfo(
        key="rejected",
        title="A scan that gets rejected",
        blurb="A real public test image with only one slice.",
        shows=(
            "The quality check refuses it, with a plain-language reason, and everything after it "
            "is skipped. Rejected scans are kept and explained, never silently dropped."
        ),
        synthetic=False,
        preset="",
        expected="rejected",
        approx_seconds=10,
    ),
}
UPLOAD_KEY = "upload"
UPLOAD_PRESETS = ("bone", "skin_surface", "structures")


@dataclass(frozen=True)
class BuiltDataset:
    info: DatasetInfo
    zip_bytes: bytes
    planted: tuple[PlantedIdentifier, ...] = field(default_factory=tuple)


def _rejected_zip() -> bytes:
    from pydicom.data import get_testdata_file

    path = get_testdata_file("CT_small.dcm")
    if not path:
        raise FileNotFoundError("pydicom's bundled CT_small.dcm test file is not installed")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(str(path), "IM0001.dcm")
    return buf.getvalue()


def build(key: str) -> BuiltDataset:
    if key not in DATASETS:
        raise KeyError(f"unknown sample scan {key!r}")
    info = DATASETS[key]
    if key == "rejected":
        return BuiltDataset(info, _rejected_zip())
    series = build_demo_series(key)
    return BuiltDataset(info, series.as_zip(), series.planted)


def catalogue() -> list[dict[str, object]]:
    return [
        {
            "key": d.key,
            "title": d.title,
            "blurb": d.blurb,
            "shows": d.shows,
            "synthetic": d.synthetic,
            "expected": d.expected,
            "approx_seconds": d.approx_seconds,
        }
        for d in DATASETS.values()
    ]
